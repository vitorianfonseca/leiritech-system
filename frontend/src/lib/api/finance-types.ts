/**
 * Financial operations API models (F14) — GATED + FINANCIAL.
 *
 * The backend (FastAPI) does not exist yet. These types describe the contract
 * the integration agent will fulfil; UI code depends only on these shapes,
 * never on the mock implementation, so the impl can be swapped without touching
 * callers.
 *
 * ⚠️ SAF-T COMPLIANCE BOUNDARY (BR-070 / BR-072).
 * LeiriTech tracks *payment milestones* ("marcos de pagamento"), NOT fiscal
 * documents. No field or label in this module is a "fatura" / "invoice" in the
 * fiscal sense. `externalInvoiceRef` is a PLAIN reference string that points at
 * a document generated by certified fiscal software OUTSIDE LeiriTech — LeiriTech never
 * generates a fiscal document. Keep all user-facing wording non-fiscal.
 *
 * Access (BR-008 / BR-066 / BR-069): financial data is visible to Admin ✅ and
 * to Gestor 🔒 only with an explicit payments grant. It is ENTIRELY hidden from
 * Membro — the API refuses to return data for them.
 */

import type { Role } from "@/lib/session";

/**
 * Payment-milestone lifecycle (WORKFLOW_SPEC §1.7).
 *
 * Note: the enum *value* `invoiced` is an internal identifier (all code is in
 * English). Its user-facing label is deliberately NON-fiscal ("Emitido" /
 * "Issued" — a payment request was issued to the client), never "Faturado".
 */
export type PaymentMilestoneStatus =
  | "planned"
  | "invoiced"
  | "partially_paid"
  | "paid"
  | "overdue"
  | "cancelled";

/** Cost categories tracked per project (BR-069 — Admin/grant only). */
export type ProjectCostCategory =
  | "subcontracting"
  | "software"
  | "hardware"
  | "travel"
  | "other";

export interface PaymentMilestone {
  id: string;
  projectId: string;
  projectName: string;
  clientName: string;
  /** Human description of what this milestone covers. */
  description: string;
  /** Contracted amount for the milestone, in cents (EUR). */
  amountCents: number;
  /** ISO-8601 date (yyyy-mm-dd) the payment is expected. */
  expectedDate: string;
  /** ISO date the payment request was issued to the client, or null. */
  invoicedDate: string | null;
  /** ISO date the (last) payment was received, or null. */
  paidDate: string | null;
  /** Total received so far, in cents. Drives partially_paid vs paid. */
  receivedAmountCents: number;
  /**
   * REQUIRED acceptance/completion criteria (BR-071) — what must be true for
   * this milestone to be billable. Never empty for a persisted milestone.
   */
  completionCriteria: string;
  /**
   * Plain external reference string (e.g. the number of a fiscal document
   * generated elsewhere). NOT a generated fiscal document (BR-070/072).
   */
  externalInvoiceRef: string | null;
  status: PaymentMilestoneStatus;
}

export interface ProjectCost {
  id: string;
  projectId: string;
  projectName: string;
  description: string;
  category: ProjectCostCategory;
  /** Cost amount in cents (EUR). */
  amountCents: number;
  /** ISO-8601 date the cost was incurred. */
  incurredDate: string;
}

/**
 * Live financial summary (BR-065). Recomputed from the current milestones and
 * costs on every read and after every mutation, so the margin is always live.
 */
export interface FinancialSummary {
  /** Sum of all non-cancelled milestone amounts. */
  contractedCents: number;
  /** Sum of received amounts across milestones. */
  receivedCents: number;
  /** Contracted minus received (still to collect). */
  pendingCents: number;
  /** Sum of recorded project costs. */
  costsCents: number;
  /** Logged-time cost (hours × blended rate) — mock input to the margin. */
  timeCostCents: number;
  /** Live margin = contracted − costs − time cost (BR-065). */
  marginCents: number;
  /** Margin as a fraction of contracted (0 when nothing contracted). */
  marginRatio: number;
}

/**
 * Live per-project financial rollup (BR-065), mirroring the backend's
 * authoritative `finance_service.financial_summary()` exactly:
 * `marginCents = contractedCents − laborCostCents − costsCents`, where
 * `laborCostCents` is Σ logged-hours × the project's internal cost rate.
 *
 * Consumers (e.g. the /reports Financeiro + Projetos margin tables) MUST read
 * `marginCents` from here rather than recomputing it from milestones/costs —
 * a client-side `contracted − costs` reimplementation omits labour cost and
 * silently inflates margin (see H6 in AUDIT_REPORT.md).
 */
export interface FinancialProjectSummary {
  projectId: string;
  projectName: string;
  contractedCents: number;
  receivedCents: number;
  pendingCents: number;
  /** Recorded project costs only (materials/subcontracting/etc), excludes labour. */
  costsCents: number;
  /** Σ logged hours × the project's internal cost rate. */
  laborCostCents: number;
  /** Live margin = contracted − labour cost − costs (BR-065). Backend-authoritative. */
  marginCents: number;
  /** Margin as a fraction of contracted (0 when nothing contracted). */
  marginRatio: number;
}

/** The full finance overview payload for the signed-in, authorized user. */
export interface FinanceOverview {
  summary: FinancialSummary;
  milestones: PaymentMilestone[];
  costs: ProjectCost[];
  /** Per-project rollup, one row per project with at least one milestone. */
  projectSummaries: FinancialProjectSummary[];
}

