/**
 * Pure access predicate shared by the route guard, the nav entry and the data
 * client so the three can never disagree (BR-008/066/069). Frontend gating is
 * UX only — the backend remains authoritative later.
 */
export function canAccessFinance(role: Role, paymentsGrant: boolean): boolean {
  if (role === "admin") return true;
  if (role === "gestor") return paymentsGrant;
  return false; // membro: entirely hidden
}

/** Whether the user may create/edit milestones, record payments and manage costs. */
export function canManageFinance(role: Role, paymentsGrant: boolean): boolean {
  // Same predicate today; kept distinct so integration can tighten writes
  // (e.g. read-only grant) without touching call sites.
  return canAccessFinance(role, paymentsGrant);
}

export type FinanceErrorCode = "network" | "forbidden";

export class FinanceError extends Error {
  readonly code: FinanceErrorCode;
  constructor(code: FinanceErrorCode, message?: string) {
    super(message ?? code);
    this.name = "FinanceError";
    this.code = code;
  }
}
