import { chromium } from 'playwright';
const OUT = process.env.OUT_DIR;
const b = await chromium.launch();
const p = await b.newPage({ viewport:{width:1440,height:1000} });
const errs=[]; const bad=[];
p.on('pageerror',e=>errs.push(String(e).slice(0,160)));
p.on('console',m=>{ if(m.type()==='error') errs.push(m.text().slice(0,160)); });
p.on('response',r=>{ if(r.url().includes('/api/')&&r.status()>=400) bad.push(r.status()+' '+r.url().split('/api/v1')[1]); });
await p.goto('http://localhost:3000/login',{waitUntil:'networkidle'}); await p.waitForTimeout(2500);
await p.locator('#field-email').fill('admin@leiritech.pt');
await p.locator('#field-password').fill('redesign-preview-2026');
await Promise.all([p.waitForURL(u=>!u.pathname.includes('login'),{timeout:25000}).catch(()=>{}), p.getByRole('button',{name:/Entrar|Sign in/}).click()]);
await p.waitForTimeout(4000);
console.log('URL:', p.url());
await p.screenshot({ path: `${OUT}/dash.png` });
console.log('HTTP>=400:', JSON.stringify([...new Set(bad)]));
console.log('ERROS:', JSON.stringify([...new Set(errs)].filter(e=>!/favicon|HMR|DevTools/i.test(e)).slice(0,5)));
await b.close();
